#!/usr/bin/env node
/**
 * Generates design tokens from the Figma variable snapshot.
 *
 *   tokens/figma-tokens.json  ──►  src/styles/tokens.css          (CSS variables + Tailwind @theme)
 *                             ──►  src/lib/theme/tokens.generated.ts (typed lists for code + Storybook)
 *
 * Figma structure (mirrored 1:1 in CSS):
 *   Primitives ─► Base color (7 modes) ─┐
 *              └► Theme (10 modes) ─────┴─► Mode (Light / Dark) semantic tokens
 *
 * Run: npm run tokens
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const src = JSON.parse(readFileSync(resolve(root, 'tokens/figma-tokens.json'), 'utf8'))
const C = src.collections

const slug = (s) => s.toLowerCase().replace(/\s+/g, '-')
const rem = (px) => `${+(px / 16).toFixed(4)}rem`

// ---------------------------------------------------------------- name mapping
// Figma variable name  →  CSS custom property
//   blue/600              --tbt-blue-600         (primitive; prefixed so it never clashes with Tailwind's palette)
//   base/50               --base-50
//   theme/primary-light   --theme-primary-light
//   background            --background           (semantic, shadcn naming)
const cssVar = (figmaName) => {
  if (figmaName.startsWith('base/')) return `--base-${figmaName.slice(5)}`
  if (figmaName.startsWith('theme/')) return `--theme-${figmaName.slice(6)}`
  if (figmaName.includes('/')) return `--tbt-${figmaName.replace('/', '-')}`
  return `--${figmaName}`
}
const value = (v) => {
  if (typeof v === 'string' && v.startsWith('{')) return `var(${cssVar(v.slice(1, -1))})`
  return v
}
const decls = (obj, indent = '  ') =>
  Object.entries(obj)
    .map(([k, v]) => `${indent}${cssVar(k)}: ${value(v)};`)
    .join('\n')

// ---------------------------------------------------------------- collections
const primitives = C['Primitives']['Value']
const bases = C['Base color']
const themes = C['Theme']
const modes = C['Mode']
const layout = C['TBT layout']['Mode 1']

const baseNames = Object.keys(bases).map(slug)
const themeNames = Object.keys(themes).map(slug)
const [defaultBase] = baseNames
const [defaultTheme] = themeNames
const families = [...new Set(Object.keys(primitives).map((k) => k.split('/')[0]))]
const semanticNames = Object.keys(modes.Light)

// ---------------------------------------------------------------- checks
const expect = (cond, msg) => {
  if (!cond) {
    console.error(`✖ ${msg}`)
    process.exit(1)
  }
}
expect(
  Object.keys(primitives).length === 187,
  `expected 187 primitives, got ${Object.keys(primitives).length}`,
)
expect(baseNames.length === 7, `expected 7 bases, got ${baseNames.length}`)
expect(themeNames.length === 10, `expected 10 themes, got ${themeNames.length}`)
expect(
  JSON.stringify(Object.keys(modes.Light)) === JSON.stringify(Object.keys(modes.Dark)),
  'Light and Dark must define the same semantic tokens',
)

// ---------------------------------------------------------------- CSS
const weights = { Regular: 400, Medium: 500, 'Semi Bold': 600, Bold: 700 }
const textStyles = Object.entries(src.textStyles).map(([name, s]) => ({
  figma: name,
  key: slug(name.replace(/^TBT\//, '')),
  size: s.size,
  lineHeight: s.lineHeight,
  weight: weights[s.style] ?? 400,
  letterSpacingEm: +(s.letterSpacingPercent / 100).toFixed(4),
  uppercase: s.textCase === 'UPPER',
}))

const shadow = (layers) =>
  layers.map((l) => `${l.x}px ${l.y}px ${l.blur}px ${l.spread}px ${l.color}`).join(', ')
const shadowKey = (name) =>
  slug(
    name
      .replace(/^Elevation\//, '')
      .replace(/^shadcn\//, '')
      .replace(/ ring$/, ''),
  )
const shadows = Object.entries(src.effectStyles).map(([name, layers]) => ({
  figma: name,
  key: shadowKey(name),
  css: shadow(layers),
}))

const radii = Object.entries(layout)
  .filter(([k]) => k.startsWith('radius/'))
  .map(([k, px]) => ({ key: k.slice(7), px }))
const spacing = Object.entries(layout)
  .filter(([k]) => k.startsWith('space/'))
  .map(([k, px]) => ({ figma: k, px, tailwind: String(px / 4) }))

// Selectors: semantic tokens are re-declared wherever a base/theme is set,
// so nested scopes (e.g. a preview card with data-theme="pink") resolve correctly.
const lightSel = [':root', '[data-theme]', '[data-base]'].join(',\n')
const darkSel = ['.dark', '.dark [data-theme]', '.dark [data-base]'].join(',\n')

const css = `/*
 * AUTO-GENERATED by scripts/generate-tokens.mjs from tokens/figma-tokens.json
 * (Figma: ${src.source.file}, exported ${src.source.exportedAt}). Do not edit by hand. Run \`npm run tokens\`.
 *
 * Usage on any element (usually <html>):
 *   class="dark"            Mode     light (default) | dark
 *   data-theme="${defaultTheme}"     Accent   ${themeNames.join(' | ')}
 *   data-base="${defaultBase}"    Base     ${baseNames.join(' | ')}
 */

/* ── Primitives (${Object.keys(primitives).length}) ─────────────────────────────── */
:root {
${decls(primitives)}
}

/* ── Base color (${baseNames.length}) ── neutral family behind every surface ────── */
${Object.entries(bases)
  .map(
    ([name, vars], i) =>
      `${i === 0 ? ':root,\n' : ''}[data-base='${slug(name)}'] {\n${decls(vars)}\n}`,
  )
  .join('\n\n')}

/* ── Theme (${themeNames.length}) ── accent for primary + charts ─────────────── */
${Object.entries(themes)
  .map(
    ([name, vars], i) =>
      `${i === 0 ? ':root,\n' : ''}[data-theme='${slug(name)}'] {\n${decls(vars)}\n}`,
  )
  .join('\n\n')}

/* ── Mode: Light ─────────────────────────────────────────────── */
${lightSel} {
${decls(modes.Light)}
}

/* ── Mode: Dark ──────────────────────────────────────────────── */
${darkSel} {
${decls(modes.Dark)}
}

/* ── Tailwind theme: radius, type, elevation (from Figma) ────── */
@theme {
${radii.map((r) => `  --radius-${r.key}: ${rem(r.px)}; /* ${r.px}px */`).join('\n')}

${textStyles
  .map((t) =>
    [
      `  /* ${t.figma}${t.uppercase ? ' (uppercase)' : ''} */`,
      `  --text-${t.key}: ${rem(t.size)};`,
      `  --text-${t.key}--line-height: ${rem(t.lineHeight)};`,
      `  --text-${t.key}--letter-spacing: ${t.letterSpacingEm}em;`,
      `  --text-${t.key}--font-weight: ${t.weight};`,
    ].join('\n'),
  )
  .join('\n')}

${shadows.map((s) => `  --shadow-${s.key}: ${s.css}; /* ${s.figma} */`).join('\n')}
}
`

// ---------------------------------------------------------------- TS
const ts = `/*
 * AUTO-GENERATED by scripts/generate-tokens.mjs from tokens/figma-tokens.json.
 * Do not edit by hand. Run \`npm run tokens\`.
 */

export const ACCENTS = ${JSON.stringify(themeNames)} as const
export type Accent = (typeof ACCENTS)[number]
export const DEFAULT_ACCENT: Accent = '${defaultTheme}'

export const BASES = ${JSON.stringify(baseNames)} as const
export type Base = (typeof BASES)[number]
export const DEFAULT_BASE: Base = '${defaultBase}'

export const PRIMITIVE_FAMILIES = ${JSON.stringify(families)} as const
export const SHADES = ${JSON.stringify(['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'])} as const

/** Semantic color tokens (Mode collection). Tailwind: bg-{name}, text-{name}, border-{name}. */
export const SEMANTIC_COLORS = ${JSON.stringify(semanticNames)} as const
export type SemanticColor = (typeof SEMANTIC_COLORS)[number]

/** Type scale. Tailwind: text-{key} (sets size, line-height, letter-spacing and weight). */
export const TEXT_STYLES = ${JSON.stringify(textStyles, null, 2)} as const

/** Spacing (TBT layout). Figma space/{px} = Tailwind spacing {px / 4} (e.g. space/16 → p-4). */
export const SPACING = ${JSON.stringify(spacing, null, 2)} as const

/** Corner radius. Tailwind: rounded-{key}. */
export const RADII = ${JSON.stringify(radii, null, 2)} as const

/** Elevation. Tailwind: shadow-{key}. */
export const SHADOWS = ${JSON.stringify(shadows, null, 2)} as const
`

writeFileSync(resolve(root, 'src/styles/tokens.css'), css)
writeFileSync(resolve(root, 'src/lib/theme/tokens.generated.ts'), ts)
console.log(
  `✔ tokens: ${Object.keys(primitives).length} primitives, ${baseNames.length} bases, ${themeNames.length} accents, ` +
    `${semanticNames.length} semantic × 2 modes, ${textStyles.length} text styles, ${shadows.length} shadows, ${radii.length} radii`,
)
